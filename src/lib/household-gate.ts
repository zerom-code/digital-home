/**
 * Что показать на входе в приложение: дом, онбординг, ошибку или ожидание.
 *
 * Логика вынесена из App.tsx отдельно и покрыта тестами не для красоты.
 * Ошибка здесь не косметическая: онбординг предлагает **создать дом**, и
 * показать его человеку, у которого дом уже есть, — значит завести второй
 * поверх первого. Обратной дороги нет, а повторяется это при каждом запуске.
 * Ровно так и случилось дважды подряд, потому что «дома нет» и «ответа пока
 * нет» были неотличимы (см. useHousehold.ts).
 */

export interface HouseholdGate {
  /** Сервер ответил именно в этот запуск — на ответ можно опираться. */
  isConfirmed: boolean;
  /** Дом найден: в свежем ответе или в кеше, показанном до ответа. */
  hasHousehold: boolean;
  /** Показать пока нечего: ни ответа, ни кеша. */
  isLoading: boolean;
  /** Запрос закончился ошибкой. */
  hasError: boolean;
  /** Человек пришёл по ссылке-приглашению — своего онбординга там нет. */
  isJoining: boolean;
}

export type GateScreen = 'loading' | 'error' | 'onboarding' | 'app';

export function decideScreen(gate: HouseholdGate): GateScreen {
  // Есть что показать — показываем, даже если ответ ещё в пути или уже
  // не пришёл. Кешированный дом лучше спиннера и куда лучше онбординга
  if (gate.hasHousehold) return 'app';

  if (gate.isLoading) return 'loading';

  // Сеть отвалилась и кеша нет. Отправить отсюда в онбординг — предложить
  // создать второй дом вместо того, к которому не достучались
  if (gate.hasError) return 'error';

  // Приглашение ведёт в чужой, уже существующий дом
  if (gate.isJoining) return 'app';

  // Единственный случай, когда предлагать создать дом безопасно: сервер
  // ответил в этот запуск, и в ответе пусто
  if (gate.isConfirmed) return 'onboarding';

  // Ответа ещё нет — ждём. Раньше сюда проваливалось «дома нет»
  return 'loading';
}
